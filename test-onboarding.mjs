async function honesty(p,where){
  const t=await p.evaluate(()=>document.body.innerText)
  for(const [re,name] of BAD) if(re.test(t)) fail(`${where} contains “${name}”`)
  if(t.includes('${')) fail(`${where} has raw template text`)
  const o=await p.evaluate(()=>document.documentElement.scrollWidth-innerWidth)
  if(o>1) fail(`${where} horizontal overflow ${o}px`)
  return t
}
